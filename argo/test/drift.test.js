test('normaliseSystem handles both shapes the Messages API accepts', () => {
  assert.deepEqual(normaliseSystem('a plain string prompt'), {
    blocks: [{ index: 0, text: 'a plain string prompt', cached: false, chars: 21 }],
    text: 'a plain string prompt',
  })

  const arr = normaliseSystem([
    { type: 'text', text: 'first', cache_control: { type: 'ephemeral' } },
    { type: 'text', text: 'second' },
  ])
  assert.equal(arr.text, 'first\n\nsecond')
  assert.deepEqual(arr.blocks.map((b) => b.cached), [true, false])
  assert.deepEqual(arr.blocks.map((b) => b.index), [0, 1])
})

test('normaliseSystem degrades instead of throwing on junk', () => {
  assert.deepEqual(normaliseSystem(null), { blocks: [], text: '' })
  assert.deepEqual(normaliseSystem(undefined), { blocks: [], text: '' })
  assert.deepEqual(normaliseSystem(42), { blocks: [], text: '' })
  // A block with no text field yields an empty block, not the string "undefined".
  assert.deepEqual(normaliseSystem([{ notText: 1 }]).blocks[0], {
    index: 0, text: '', cached: false, chars: 0,
  })
})

const PROMPT_A = `You are Claude Code.

# Tool use

You may call tools to accomplish the task.

# Delegation

Use the AgentTool to fan out when the task list has independent items.`

const PROMPT_B = `You are Claude Code.

# Tool use

You may call tools to accomplish the task.

# Delegation

Do not call the AgentTool unless the user requested it.

# Safety

Never read another worker's draft output.`

test('sections splits a delivered prompt on its headings', () => {
  const s = sections(PROMPT_A)
  assert.deepEqual(s.map((x) => x.heading), ['(preamble)', 'Tool use', 'Delegation'])
  assert.equal(s[0].body, 'You are Claude Code.')
  assert.ok(s[2].body.includes('AgentTool'))
  assert.equal(s[0].hash.length, 12)
})

test('sections hashes are stable and change only with content', () => {
  const a = sections(PROMPT_A)
  const b = sections(PROMPT_A)
  assert.deepEqual(a.map((x) => x.hash), b.map((x) => x.hash))
  const changed = sections(PROMPT_B)
  const toolUseA = a.find((x) => x.heading === 'Tool use')
  const toolUseB = changed.find((x) => x.heading === 'Tool use')
  assert.equal(toolUseA.hash, toolUseB.hash, 'untouched section keeps its hash')
})

test('sections copes with an empty or heading-free prompt', () => {
  assert.deepEqual(sections(''), [])
  assert.deepEqual(sections(null), [])
  const plain = sections('just one paragraph with no heading at all')
  assert.equal(plain.length, 1)
  assert.equal(plain[0].heading, '(preamble)')
})

test('policySentences pulls the imperative lines out of a delivered prompt', () => {
  const found = policySentences(PROMPT_B)
  assert.ok(found.includes('Do not call the AgentTool unless the user requested it.'))
  assert.ok(found.includes("Never read another worker's draft output."))
  assert.equal(policySentences(PROMPT_A).length, 0)
  assert.deepEqual(policySentences(''), [])
  assert.deepEqual(policySentences(null), [])
})

test('toolGateSentences finds every mention of a delegation tool', () => {
  assert.deepEqual(toolGateSentences(PROMPT_A), [
    'You may call tools to accomplish the task.',
    'Use the AgentTool to fan out when the task list has independent items.',
  ])
  assert.deepEqual(toolGateSentences('nothing relevant in this sentence at all'), [])
  assert.deepEqual(toolGateSentences('Do not spawn a subagent for a one-line edit.', ['subagent']), [
    'Do not spawn a subagent for a one-line edit.',
  ])
})

test('diffPrompts reports the section that changed and the constraint that landed', () => {
  const d = diffPrompts(PROMPT_A, PROMPT_B)
  assert.deepEqual(d.added.map((s) => s.heading), ['Safety'])
  assert.deepEqual(d.removed, [])
  assert.deepEqual(d.changed.map((c) => c.heading), ['Delegation'])
  assert.ok(d.policyAdded.includes('Do not call the AgentTool unless the user requested it.'))
  assert.ok(d.policyAdded.includes("Never read another worker's draft output."))
  assert.deepEqual(d.policyRemoved, [])
  assert.equal(d.charsBefore, PROMPT_A.length)
  assert.equal(d.charsAfter, PROMPT_B.length)
})

test('diffPrompts is empty for an unchanged prompt and survives empties', () => {
  const same = diffPrompts(PROMPT_A, PROMPT_A)
  assert.deepEqual(same.added, [])
  assert.deepEqual(same.removed, [])
  assert.deepEqual(same.changed, [])
  assert.deepEqual(same.policyAdded, [])
  const empty = diffPrompts(null, undefined)
  assert.deepEqual(empty.policyAdded, [])
  assert.equal(empty.charsBefore, 0)
})

test('diffPrompts reports a removed section, not just an added one', () => {
  const d = diffPrompts(PROMPT_B, PROMPT_A)
  assert.deepEqual(d.removed.map((s) => s.heading), ['Safety'])
  assert.deepEqual(d.added, [])
  assert.ok(d.policyRemoved.includes('Do not call the AgentTool unless the user requested it.'))
  assert.deepEqual(d.policyAdded, [])
})

/* ------------------------------------------------------------------ *
 * selfreport.js — grading a first-person report of the delegation gate
 * ------------------------------------------------------------------ */

test('classifySentence needs BOTH a mechanism and a restriction to call it a gate', () => {
  const gate = classifySentence('Do not call the AgentTool unless the user requested it.')
  assert.equal(gate.isGate, true)
  assert.ok(gate.mechanisms.includes('agent-tool'))
  assert.ok(gate.restrictions.includes('user-gated'))

  // Names the mechanism, restricts nothing — that is documentation.
  const mention = classifySentence('Use the AgentTool to fan out across independent files.')
  assert.equal(mention.isGate, false)
  assert.ok(mention.mechanisms.includes('agent-tool'))
  assert.deepEqual(mention.restrictions, [])

  // Restricts something, names no delegation mechanism — unrelated policy.
  assert.equal(classifySentence('Never delete a file you did not create.'), null)
  assert.equal(classifySentence(''), null)
  assert.equal(classifySentence(null), null)
})

test('classifySentence scores a user-conditional gate above a bare prohibition', () => {
  const strong = classifySentence('Do not call the AgentTool unless the user requested it.')
  const weaker = classifySentence('Avoid using subagents here.')
  assert.ok(strong.score > weaker.score, `${strong.score} should exceed ${weaker.score}`)
})

test('parseSelfReport reads the GATE: line format and tolerates preamble', () => {
  const parsed = parseSelfReport(`
    Here is what I found in my instructions:
    GATE: Do not call the AgentTool unless the user requested it.
    GATE: "Use subagents in parallel for independent work."
    Hope that helps!
  `)
  assert.equal(parsed.declaredNone, false)
  assert.equal(parsed.sentences.length, 2)
  assert.equal(parsed.gates.length, 1)
  assert.equal(parsed.mentions.length, 1)
  // Surrounding quotes are stripped so the same sentence diffs equal next time.
  assert.equal(parsed.sentences[1], 'Use subagents in parallel for independent work.')
})

test('parseSelfReport recognises an explicit NONE', () => {
  const parsed = parseSelfReport('NONE')
  assert.equal(parsed.declaredNone, true)
  assert.deepEqual(parsed.gates, [])
  // A NONE alongside a GATE line is not a NONE.
  assert.equal(parseSelfReport('NONE\nGATE: Never use the AgentTool.').declaredNone, false)
  assert.equal(parseSelfReport('').declaredNone, false)
})

test('confidence never reports a self-report as ground truth', () => {
  const strong = confidence(parseSelfReport('GATE: Do not call the AgentTool unless the user requested it.'))
  assert.equal(strong.level, 'strong')

  const none = confidence(parseSelfReport('NONE'))
  assert.equal(none.level, 'reported-absent')
  assert.match(none.note, /confirm behaviourally/i)

  const inconclusive = confidence(parseSelfReport('GATE: Use the AgentTool to fan out.'))
  assert.equal(inconclusive.level, 'inconclusive')
  assert.equal(inconclusive.score, 0)
})

test('buildRecord is deterministic when the timestamp is supplied', () => {
  const args = {
    text: 'GATE: Do not call the AgentTool unless the user requested it.',
    model: 'claude-opus-5',
    capturedAt: '2026-08-17T00:00:00.000Z',
  }
  const a = buildRecord(args)
  const b = buildRecord(args)
  assert.deepEqual(a, b)
  assert.equal(a.hash.length, 16)
  assert.equal(a.kind, 'self-report')
  assert.equal(a.gates.length, 1)
  // The stored record must carry its own caveat, so the file cannot be
  // mistaken for a byte capture later.
  assert.match(a.caveat, /not captured off the wire/i)
})

test('diffSelfReports shows a gate appearing between two reports', () => {
  const before = buildRecord({ text: 'NONE', capturedAt: '2026-08-16T00:00:00.000Z' })
  const after = buildRecord({
    text: 'GATE: Do not call the AgentTool unless the user requested it.',
    capturedAt: '2026-08-17T00:00:00.000Z',
  })
  const d = diffSelfReports(before, after)
  assert.deepEqual(d.added, ['Do not call the AgentTool unless the user requested it.'])
  assert.deepEqual(d.removed, [])
  assert.deepEqual(d.unchanged, [])

  const same = diffSelfReports(after, after)
  assert.deepEqual(same.added, [])
  assert.equal(same.unchanged.length, 1)
})

