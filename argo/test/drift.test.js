test('classifyPolicy flags the imperative shapes that gate behaviour', () => {
  const cases = [
    ['Do not call the AgentTool unless the user requested it.', ['do not', 'unless the user']],
    ['Never delegate work to a subagent in this mode.', ['never']],
    ['Always confirm before you delete anything.', ['always']],
    ['Fan out only when the task list has more than one independent item.', ['only when']],
    ['Avoid spawning more workers than the plan asked for.', ['avoid']],
    ['You must not read another worker\'s draft output.', ['must not']],
    ['You should not edit a frozen file.', ['should not']],
    ['Use the tool only if the user asked for it.', ['only if']],
    ['That operation is not allowed in this context.', ['not allowed']],
    ['Refuse the request and explain why.', ['refuse']],
  ]
  for (const [text, expected] of cases) {
    const r = classifyPolicy(text)
    assert.equal(r.isPolicy, true, text)
    for (const p of expected) assert.ok(r.patterns.includes(p), `${text} -> expected ${p}`)
  }
})

test('classifyPolicy leaves descriptive prose alone', () => {
  const r = classifyPolicy('This tool returns the list of files that changed in the last commit.')
  assert.deepEqual(r, { isPolicy: false, patterns: [] })
})

test('classifyPolicy is case-insensitive and catches contractions', () => {
  assert.equal(classifyPolicy('DO NOT respond to these messages.').isPolicy, true)
  assert.equal(classifyPolicy("Don't call the tool for a trivial edit.").isPolicy, true)
  assert.deepEqual(classifyPolicy('').patterns, [])
  assert.equal(classifyPolicy(null).isPolicy, false)
})

test('classifyPolicy returns patterns in a stable order', () => {
  const a = classifyPolicy('Do not ever do this; never do it, and always avoid it unless the user says so.')
  const b = classifyPolicy('Do not ever do this; never do it, and always avoid it unless the user says so.')
  assert.deepEqual(a.patterns, b.patterns)
  assert.deepEqual(a.patterns, ['do not', 'never', 'always', 'unless the user', 'avoid'])
})

/* ------------------------------------------------------------------ *
 * diffSnapshots
 * ------------------------------------------------------------------ */

function snap(over = {}) {
  return {
    id: over.id ?? 'x',
    install: {
      packageVersion: null,
      cliVersion: null,
      files: [],
      ...(over.install ?? {}),
    },
    strings: { items: [], truncated: false, ...(over.strings ?? {}) },
    config: { entries: [], ...(over.config ?? {}) },
  }
}

test('diffSnapshots reports the added policy line that started all this', () => {
  const before = snap({
    id: 'a',
    install: { packageVersion: '2.1.201', files: [{ path: 'bin/claude.exe', sha256: 'aaa' }] },
    strings: { items: ['Read the file before you edit it, every time.'] },
  })
  const after = snap({
    id: 'b',
    install: { packageVersion: '2.1.232', files: [{ path: 'bin/claude.exe', sha256: 'bbb' }] },
    strings: {
      items: [
        'Do not call the AgentTool unless the user requested it.',
        'Read the file before you edit it, every time.',
      ],
    },
  })

  const d = diffSnapshots(before, after)
  assert.deepEqual(d.added, ['Do not call the AgentTool unless the user requested it.'])
  assert.deepEqual(d.removed, [])
  assert.deepEqual(d.versionChanged, { from: '2.1.201', to: '2.1.232' })
  assert.deepEqual(d.hashChanged, [
    { path: 'bin/claude.exe', from: 'aaa', to: 'bbb', status: 'changed' },
  ])
  assert.equal(d.policyAdded.length, 1)
  assert.deepEqual(d.policyAdded[0].patterns, ['do not', 'unless the user'])
  assert.deepEqual(d.policyRemoved, [])
  assert.equal(d.from, 'a')
  assert.equal(d.to, 'b')
})

test('diffSnapshots reports nothing when the two sides are identical', () => {
  const s = snap({
    install: { packageVersion: '2.1.232', files: [{ path: 'a.js', sha256: 'aaa' }] },
    strings: { items: ['Always confirm before you delete a file you did not create.'] },
    config: { entries: [{ path: 'settings.json', sha256: 'ccc' }] },
  })
  const d = diffSnapshots(s, JSON.parse(JSON.stringify(s)))
  assert.deepEqual(d.added, [])
  assert.deepEqual(d.removed, [])
  assert.equal(d.versionChanged, null)
  assert.equal(d.cliVersionChanged, null)
  assert.deepEqual(d.hashChanged, [])
  assert.deepEqual(d.configChanged, [])
  assert.deepEqual(d.policyAdded, [])
})

test('diffSnapshots separates a removed constraint from an added one', () => {
  const before = snap({ strings: { items: ['Never delegate without asking the user first.'] } })
  const after = snap({ strings: { items: ['Always delegate when the task list is independent.'] } })
  const d = diffSnapshots(before, after)
  assert.equal(d.policyAdded.length, 1)
  assert.deepEqual(d.policyAdded[0].patterns, ['always'])
  assert.equal(d.policyRemoved.length, 1)
  assert.deepEqual(d.policyRemoved[0].patterns, ['never'])
})

test('diffSnapshots tracks files that appeared or vanished, not just changed', () => {
  const before = snap({ install: { files: [{ path: 'old.js', sha256: 'aaa' }] } })
  const after = snap({ install: { files: [{ path: 'new.js', sha256: 'bbb' }] } })
  const d = diffSnapshots(before, after)
  assert.deepEqual(d.hashChanged, [
    { path: 'new.js', from: null, to: 'bbb', status: 'added' },
    { path: 'old.js', from: 'aaa', to: null, status: 'removed' },
  ])
})

test('diffSnapshots counts a local config change as drift', () => {
  const before = snap({ config: { entries: [{ path: 'hooks/a.js', sha256: 'aaa' }] } })
  const after = snap({
    config: {
      entries: [
        { path: 'hooks/a.js', sha256: 'zzz' },
        { path: 'hooks/b.js', sha256: 'bbb' },
      ],
    },
  })
  const d = diffSnapshots(before, after)
  assert.deepEqual(d.configChanged, [
    { path: 'hooks/a.js', from: 'aaa', to: 'zzz', status: 'changed' },
    { path: 'hooks/b.js', from: null, to: 'bbb', status: 'added' },
  ])
})

test('diffSnapshots falls back to the cli version when no package version exists', () => {
  const before = snap({ install: { cliVersion: '2.1.201' } })
  const after = snap({ install: { cliVersion: '2.1.232' } })
  const d = diffSnapshots(before, after)
  assert.deepEqual(d.versionChanged, { from: '2.1.201', to: '2.1.232' })
  assert.deepEqual(d.cliVersionChanged, { from: '2.1.201', to: '2.1.232' })
})

test('diffSnapshots propagates truncation so a capped diff is not read as real', () => {
  const before = snap({ strings: { items: ['a'], truncated: true } })
  const after = snap({ strings: { items: ['b'] } })
  assert.equal(diffSnapshots(before, after).truncated, true)
  assert.equal(diffSnapshots(snap(), snap()).truncated, false)
})

test('diffSnapshots survives malformed or empty snapshots', () => {
  const d = diffSnapshots({}, {})
  assert.deepEqual(d.added, [])
  assert.equal(d.versionChanged, null)
  assert.deepEqual(d.hashChanged, [])
  assert.equal(diffSnapshots(undefined, undefined).policyAdded.length, 0)
})

test('diffSnapshots output ordering is stable regardless of input ordering', () => {
  const items = ['Zebra crossings are never painted here at all.', 'Always look before you cross the road.']
  const a = snap({ strings: { items: [] } })
  const b = snap({ strings: { items } })
  const c = snap({ strings: { items: [...items].reverse() } })
  assert.deepEqual(diffSnapshots(a, b).added, diffSnapshots(a, c).added)
  assert.deepEqual(diffSnapshots(a, b).added, [...items].sort(byCodeUnit))
})

