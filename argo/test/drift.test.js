const FAKE_BUNDLE =
  'var t=0;const A="Do not call the AgentTool unless the user requested it, or you were told to.";' +
  'const B={mode:"fast",n:42};function q(a,b){return a<b?a:b}' +
  'const C="Always confirm with the user before you delete a file that you did not create.";' +
  'const D="Do not call the AgentTool unless the user requested it, or you were told to.";' +
  'const E="useSyncExternalStoreuseImperativeHandleuseInsertionEffect";'

test('extractStrings pulls prose out of a bundle and drops the code around it', () => {
  const out = extractStrings(FAKE_BUNDLE)
  assert.deepEqual(out, [
    'Always confirm with the user before you delete a file that you did not create.',
    'Do not call the AgentTool unless the user requested it, or you were told to.',
  ])
})

test('extractStrings is deduped, sorted by code unit, and reproducible', () => {
  const a = extractStrings(FAKE_BUNDLE)
  const b = extractStrings(FAKE_BUNDLE)
  assert.deepEqual(a, b)
  assert.deepEqual([...a].sort(byCodeUnit), a)
  assert.equal(new Set(a).size, a.length)
})

test('extractStrings accepts a Buffer as well as a string', () => {
  assert.deepEqual(extractStrings(Buffer.from(FAKE_BUNDLE, 'latin1')), extractStrings(FAKE_BUNDLE))
})

test('extractStrings splits on the escaped newlines a multi-line prompt is stored with', () => {
  const packed =
    '"You are a helpful assistant that answers the question asked.' +
    '\\nDo not call the AgentTool unless the user requested it here.' +
    '\\nAlways report what you changed before you finish the turn."'
  const out = extractStrings(packed)
  assert.equal(out.length, 3)
  assert.ok(out.includes('Do not call the AgentTool unless the user requested it here.'))
  assert.ok(out.includes('Always report what you changed before you finish the turn.'))
})

test('extractStrings ignores binary noise between literals', () => {
  const noisy = Buffer.concat([
    Buffer.from([0, 1, 2, 255, 254, 7]),
    Buffer.from('Do not call the AgentTool unless the user requested it here.', 'latin1'),
    Buffer.from([0, 0, 3, 200]),
  ])
  assert.deepEqual(extractStrings(noisy), [
    'Do not call the AgentTool unless the user requested it here.',
  ])
})

