// Rebuild the Tier-3 skill-library index. Run after `git pull` in any repo under dskills/.
// Emits INDEX.md: one line per skill (repo, name, description, path) so the router skill can
// grep it on demand instead of every skill sitting in session context.
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import { join, relative, sep, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = process.env.LIBRARY_ROOT || join(dirname(fileURLToPath(import.meta.url)), "repos")
const SKIP = new Set(['.git', 'node_modules', '_index', 'dist', 'build'])

// Path fragments this index deliberately does not carry. The library on disk is third-party
// and may hold material this repo does not want to surface or name; skipping it here rather
// than hand-editing INDEX.md is what makes the omission survive the next regeneration.
// Each entry is matched against the skill's path relative to the library root.
const EXCLUDE = [`discord-com${sep}`]

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue
    const p = join(dir, e.name)
    if (e.isDirectory()) walk(p, out)
    else if (e.name === 'SKILL.md') out.push(p)
  }
  return out
}

function frontmatter(file) {
  const lines = readFileSync(file, 'utf8').split(/\r?\n/)
  if (lines[0]?.trim() !== '---') return null
  const end = lines.indexOf('---', 1)
  if (end < 0) return null
  const fm = {}
  for (const l of lines.slice(1, end)) {
    const m = l.match(/^(name|description):\s*(.*)$/)
    if (m) fm[m[1]] = m[2].replace(/^["']|["']$/g, '').trim()
  }
  return fm.name ? fm : null
}

const rows = []
for (const f of walk(ROOT)) {
  const fm = frontmatter(f)
  if (!fm) continue
  const rel = relative(ROOT, f)
  if (EXCLUDE.some((frag) => rel.includes(frag))) continue
  rows.push({ repo: rel.split(sep)[0], name: fm.name, desc: (fm.description || '').replace(/\s+/g, ' ').slice(0, 300), path: rel })
}
rows.sort((a, b) => a.repo.localeCompare(b.repo) || a.name.localeCompare(b.name))

const byRepo = {}
for (const r of rows) (byRepo[r.repo] ??= []).push(r)

let md = `# Tier-3 skill library index\n\nGenerated by \`_index/build-index.mjs\`. ${rows.length} skills across ${Object.keys(byRepo).length} repos.\nThese are NOT loaded into session context. Grep this file, then read the specific SKILL.md by path.\n\n`
for (const [repo, list] of Object.entries(byRepo)) {
  md += `## ${repo} (${list.length})\n\n`
  for (const r of list) md += `- **${r.name}** — ${r.desc || '(no description)'}\n  \`${r.path}\`\n`
  md += '\n'
}
writeFileSync(join(ROOT, '_index', 'INDEX.md'), md, 'utf8')
console.log(`  ${rows.length} skills indexed across ${Object.keys(byRepo).length} repos`)
for (const [repo, list] of Object.entries(byRepo)) console.log(`    ${repo.padEnd(24)} ${String(list.length).padStart(4)}`)
